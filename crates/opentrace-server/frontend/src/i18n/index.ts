import { useEffect, useState } from 'react';

export type Lang = 'zh' | 'en';

const STORAGE_KEY = 'ot-lang';
const LANG_CHANGE_EVENT = 'ot-lang-change';

export function getLang(): Lang {
  const stored = localStorage.getItem(STORAGE_KEY);
  if (stored === 'zh' || stored === 'en') return stored;
  return navigator.language.startsWith('zh') ? 'zh' : 'en';
}

export function setLang(lang: Lang): void {
  localStorage.setItem(STORAGE_KEY, lang);
  window.dispatchEvent(new CustomEvent<Lang>(LANG_CHANGE_EVENT, { detail: lang }));
}

export function toggleLang(): void {
  const current = getLang();
  const next = current === 'zh' ? 'en' : 'zh';
  setLang(next);
}

export function useLang(): Lang {
  const [lang, setCurrentLang] = useState<Lang>(getLang);

  useEffect(() => {
    const handleChange = () => setCurrentLang(getLang());
    window.addEventListener(LANG_CHANGE_EVENT, handleChange);
    window.addEventListener('storage', handleChange);
    return () => {
      window.removeEventListener(LANG_CHANGE_EVENT, handleChange);
      window.removeEventListener('storage', handleChange);
    };
  }, []);

  return lang;
}

export function t(key: string): string {
  const lang = getLang();
  return translations[lang]?.[key] || translations['en']?.[key] || key;
}

